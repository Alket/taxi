for (const locale of LOCALES) {
  const file = path.join(ROOT, `${locale}.json`)
  const current = JSON.parse(fs.readFileSync(file, "utf8")) as Dict
  const merged = { ...current, ...KEYS[locale] }
  // Keep stable key order: existing keys first, then new ones alphabetically for new-only
  const out: Dict = {}
  for (const key of Object.keys(current)) out[key] = merged[key]
  for (const key of Object.keys(KEYS[locale]).sort()) {
    if (!(key in out)) out[key] = KEYS[locale][key]
  }
  // Also ensure EN keys exist in every locale (fallback fill)
  for (const key of Object.keys(KEYS.en)) {
    if (!(key in out)) out[key] = KEYS[locale][key] ?? KEYS.en[key]
  }
  fs.writeFileSync(file, `${JSON.stringify(out, null, 2)}\n`)
  console.log(`updated ${locale}.json (+${Object.keys(KEYS[locale]).length} keys)`)
}
